"""
Deep Review service: unlimited local deep synthesis.

Move 1 of the competitor playbook. Rival Deep Reviews are
credit-metered (Consensus 3 free per month, SciSpace 100 credits per
month); this pipeline runs entirely on the local model, so there is
no credit cap - the only limit is the per-IP rate limit on the
endpoint. Retrieval-first design: the model only ever summarises
retrieved abstracts, never recalls facts from memory.

Pipeline:
1. Derive 2-3 sub-queries from the research question (local LLM,
   keyword fallback when the model is unavailable).
2. Search OpenAlex and Semantic Scholar for each sub-query.
3. Screen the merged results: dedupe by DOI (title fallback), drop
   items with no abstract.
4. Extract a short structured finding per paper with the local LLM
   (problem, method, key result, one quoted sentence copied from the
   abstract). The quote is checked against the abstract and replaced
   with the abstract's first sentence when it does not match, so a
   quoted sentence is always a real sentence from the paper.
5. Synthesize a cited report with the local LLM where every claim
   cites the paper it came from as [n].
"""
import json
import logging
import re
from typing import Any, Dict, List, Optional

from . import openalex_service, semantic_scholar_service
from .crossref_service import fetch_crossref_papers
from .europe_pmc_service import fetch_europe_pmc_papers
from .llm_provider import get_chat_model
from .openalex_service import fetch_openalex_papers
from .semantic_scholar_service import fetch_semantic_scholar_papers

logger = logging.getLogger(__name__)

VERIFICATION_NOTE = (
    "This report was generated by a local language model from the "
    "abstracts listed below. It is a starting point, not a finished "
    "literature review: check the cited papers yourself before relying "
    "on any claim."
)


def _normalize_doi(raw: object) -> str:
    if not raw:
        return ""
    doi = str(raw).strip()
    for prefix in ("https://doi.org/", "http://doi.org/", "doi:"):
        if doi.lower().startswith(prefix):
            doi = doi[len(prefix):]
            break
    return doi.lower()


def _paper_doi(paper: Dict[str, Any]) -> str:
    external = paper.get("externalIds") or {}
    if isinstance(external, dict):
        for key in ("DOI", "doi"):
            if external.get(key):
                return _normalize_doi(external[key])
    return _normalize_doi(paper.get("doi"))


def _normalize_paper(paper: Dict[str, Any]) -> Dict[str, Any]:
    authors = paper.get("authors") or []
    if authors and isinstance(authors[0], dict):
        authors = [a.get("name", "") for a in authors if a.get("name")]
    return {
        "title": (paper.get("title") or "Untitled").strip(),
        "abstract": (paper.get("abstract") or "").strip(),
        "authors": authors,
        "year": paper.get("year"),
        "venue": paper.get("venue") or "",
        "doi": _paper_doi(paper),
        "url": paper.get("url") or "",
        "citation_count": int(paper.get("citationCount") or 0),
        "source": paper.get("source") or "Unknown",
    }


def _first_sentence(text: str) -> str:
    sentences = [s.strip() for s in re.split(r"(?<=[.!?])\s+", text.strip()) if s.strip()]
    return sentences[0] if sentences else text.strip()[:300]


def derive_subqueries(question: str) -> List[str]:
    """Derive 2-3 search sub-queries from a research question.

    Uses the local LLM once; on any failure falls back to keyword
    variants of the question itself, so the pipeline never depends
    on the model being up.
    """
    fallback = [question]
    words = [w for w in re.findall(r"\b[a-z]{4,}\b", question.lower())]
    if words:
        fallback.append(" ".join(words[:6]))
    fallback.append(question + " systematic review")
    try:
        llm = get_chat_model(temperature=0.0)
        prompt = (
            "Rewrite this research question as 3 short keyword search "
            "queries for an academic paper database, one per line, no "
            "numbering, no hyphens, words separated by spaces, no extra text.\n\n"
            f"Research question: {question}\n\nQueries:"
        )
        response = llm.invoke(prompt)
        content = response.content if isinstance(response.content, str) else str(response.content)
        queries = [line.strip(" -0123456789.)") for line in content.strip().splitlines()]
        queries = [q for q in queries if len(q) >= 3 and q.lower() != question.lower()]
        if queries:
            seen: List[str] = []
            for q in queries:
                if q.lower() not in [s.lower() for s in seen]:
                    seen.append(q)
            return seen[:3]
    except Exception as e:
        logger.warning("Sub-query derivation fell back to keywords: %s", e)
    return fallback[:3]


def search_papers(subqueries: List[str], per_query: int = 10) -> List[Dict[str, Any]]:
    """Search OpenAlex and Semantic Scholar for each sub-query.

    Fallback: when the primary sources return nothing for every
    sub-query (e.g. both are rate-limiting the server's shared IP),
    retry the same sub-queries against Europe PMC and Crossref,
    which are separate free APIs with their own quotas. The fallback
    only runs when the primaries found nothing, so a normal run costs
    no extra API calls.
    """
    merged: List[Dict[str, Any]] = []
    for query in subqueries:
        try:
            df = fetch_openalex_papers(query, limit=per_query)
            if df is not None and not df.empty:
                merged.extend(df.to_dict("records"))
        except Exception as e:
            logger.warning("OpenAlex search failed for %r: %s", query, e)
        try:
            merged.extend(fetch_semantic_scholar_papers(query, limit=per_query))
        except Exception as e:
            logger.warning("Semantic Scholar search failed for %r: %s", query, e)
    if not merged:
        logger.warning("Primary sources returned nothing, trying Europe PMC and Crossref")
        for query in subqueries:
            try:
                merged.extend(fetch_europe_pmc_papers(query, limit=per_query))
            except Exception as e:
                logger.warning("Europe PMC search failed for %r: %s", query, e)
            try:
                merged.extend(fetch_crossref_papers(query, limit=per_query))
            except Exception as e:
                logger.warning("Crossref search failed for %r: %s", query, e)
    return [_normalize_paper(p) for p in merged]


def search_papers_with_status(
    subqueries: List[str], per_query: int = 10
) -> tuple[List[Dict[str, Any]], bool]:
    """Search and report whether the paper APIs failed.

    Returns (papers, search_unavailable). The second value is True
    when no papers came back and at least one source recorded an
    error (e.g. a 429 rate limit), so the caller can say "search is
    unavailable, retry later" instead of "no papers exist".
    """
    papers = search_papers(subqueries, per_query=per_query)
    unavailable = not papers and (
        openalex_service.last_error is not None
        or semantic_scholar_service.last_error is not None
    )
    return papers, unavailable


def screen_papers(papers: List[Dict[str, Any]], max_papers: int) -> List[Dict[str, Any]]:
    """Dedupe by DOI (title fallback) and drop items with no abstract."""
    seen: set = set()
    screened: List[Dict[str, Any]] = []
    for paper in papers:
        if not paper.get("abstract") or len(paper["abstract"]) < 50:
            continue
        key = _paper_doi(paper) or ("title:" + paper.get("title", "").lower())
        if key in seen:
            continue
        seen.add(key)
        screened.append(paper)
    screened.sort(key=lambda p: p.get("citation_count") or 0, reverse=True)
    return screened[:max_papers]


def _extract_json_object(content: str) -> Optional[Dict[str, str]]:
    if not content:
        return None
    start = content.find("{")
    end = content.rfind("}")
    if start == -1 or end <= start:
        return None
    try:
        parsed = json.loads(content[start:end + 1], strict=False)
    except (json.JSONDecodeError, ValueError):
        return None
    if not isinstance(parsed, dict):
        return None
    return {k: str(v or "").strip() for k, v in parsed.items()}


def extract_finding(llm, paper: Dict[str, Any], index: int) -> Dict[str, Any]:
    """Extract a structured finding from one paper's abstract."""
    abstract = paper["abstract"]
    finding: Dict[str, Any] = {
        "index": index,
        "title": paper["title"],
        "authors": paper.get("authors") or [],
        "year": paper.get("year"),
        "venue": paper.get("venue") or "",
        "doi": paper.get("doi") or "",
        "url": paper.get("url") or "",
        "source": paper.get("source") or "",
        "problem": "",
        "method": "",
        "key_result": "",
        "quote": _first_sentence(abstract),
    }
    try:
        prompt = (
            "Read this paper abstract and output ONLY a JSON object with "
            "these four keys, no other text:\n"
            '{"problem": "the research problem in one sentence", '
            '"method": "the method used in one sentence", '
            '"key_result": "the main result in one sentence", '
            '"quote": "one sentence copied exactly from the abstract"}\n\n'
            f"Title: {paper['title']}\nAbstract: {abstract[:3000]}"
        )
        response = llm.invoke(prompt)
        content = response.content if isinstance(response.content, str) else str(response.content)
        parsed = _extract_json_object(content)
        if parsed:
            for field in ("problem", "method", "key_result"):
                if parsed.get(field):
                    finding[field] = parsed[field][:600]
            if parsed.get("quote"):
                finding["quote"] = parsed["quote"][:600]
    except Exception as e:
        logger.warning("Finding extraction failed for %r, using fallback: %s", paper["title"], e)
    # Fill any missing field from the abstract itself, never from memory.
    if not finding["problem"]:
        finding["problem"] = _first_sentence(abstract)
    if not finding["method"]:
        finding["method"] = "Method not stated in the abstract."
    if not finding["key_result"]:
        finding["key_result"] = _first_sentence(abstract)
    # A quoted sentence must be a real sentence from the abstract.
    if finding["quote"] not in abstract:
        finding["quote"] = _first_sentence(abstract)
    return finding


def synthesize_report(question: str, findings: List[Dict[str, Any]]) -> str:
    """Synthesize a cited report from the per-paper findings."""
    lines = []
    for f in findings:
        lines.append(
            f"[{f['index']}] {f['title']} ({f.get('year') or 'n.d.'}). "
            f"Problem: {f['problem']} Method: {f['method']} "
            f"Key result: {f['key_result']}"
        )
    evidence = "\n".join(lines)
    try:
        llm = get_chat_model(temperature=0.0)
        prompt = (
            "Write a short literature-review style report answering the "
            "research question below, using ONLY the paper findings "
            "listed. Every claim must cite the paper it came from with "
            "its number in square brackets, like [1]. Do not add facts "
            "from any other source. If the findings disagree, say so. "
            "End with one short paragraph on what the evidence does "
            "not settle.\n\n"
            f"Research question: {question}\n\nFindings:\n{evidence}"
        )
        response = llm.invoke(prompt)
        report = response.content if isinstance(response.content, str) else str(response.content)
        report = report.strip()
        if len(report) >= 100:
            return report
    except Exception as e:
        logger.warning("Report synthesis failed, using template: %s", e)
    parts = [f"## Deep Review: {question}\n"]
    for f in findings:
        parts.append(
            f"[{f['index']}] {f['title']} ({f.get('year') or 'n.d.'}) - "
            f"{f['key_result']}"
        )
    parts.append(
        "\nWhat the evidence does not settle: the papers above were "
        "screened from abstracts only; full-text reading is needed "
        "before drawing a firm conclusion."
    )
    return "\n".join(parts)


def run_deep_review(question: str, max_papers: int = 5) -> Dict[str, Any]:
    """Run the full Deep Review pipeline for one research question."""
    subqueries = derive_subqueries(question)
    raw_papers, search_unavailable = search_papers_with_status(subqueries, per_query=10)
    screened = screen_papers(raw_papers, max_papers)
    if not screened:
        status = "search_unavailable" if search_unavailable else "no_results"
        message = (
            "The paper search APIs are rate-limiting this server right now. "
            "Wait a few minutes and retry."
            if search_unavailable
            else "No papers with abstracts were found for this question."
        )
        return {
            "status": status,
            "question": question,
            "subqueries": subqueries,
            "report": "",
            "findings": [],
            "papers_screened": 0,
            "message": message,
            "verification_note": VERIFICATION_NOTE,
        }
    llm = get_chat_model(temperature=0.0)
    findings = [extract_finding(llm, paper, i + 1) for i, paper in enumerate(screened)]
    report = synthesize_report(question, findings)
    return {
        "status": "success",
        "question": question,
        "subqueries": subqueries,
        "report": report,
        "findings": findings,
        "papers_screened": len(screened),
        "verification_note": VERIFICATION_NOTE,
    }
